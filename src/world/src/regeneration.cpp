RoomDataLoader assetRootLoader(const std::filesystem::path& assetRoot) {
    struct Cache {
        std::mutex mutex;
        std::map<std::string, std::shared_ptr<const WorldData>> data;
    };
    auto cache = std::make_shared<Cache>();
    return [assetRoot, cache](const RoomDataRequest& request) -> Expected<WorldData> {
        const std::string key = requestKey(request);
        {
            const std::lock_guard lock(cache->mutex);
            if (const auto found = cache->data.find(key); found != cache->data.end()) {
                return *found->second;
            }
        }
        auto data = loadWorldData(assetRoot, request);
        if (!data) {
            return propagate(data.error());
        }
        const std::lock_guard lock(cache->mutex);
        cache->data.emplace(key, std::make_shared<const WorldData>(*data));
        return data;
    };
}

Expected<Regeneration> regenerate(const RegenerationInput& input, const BuildingData& building,
                                  const SystemsData& systems, const RoomDataLoader& load) {
    if (Status status = checkWorldConfig(input.config); !status) {
        Error error = status.error();
        error.code = ErrorCode::InvalidArgument;
        return propagate(std::move(error));
    }
    return Regenerator(input, building, systems, load).run();
}

