std::string roomKeepReason(const WorldPlan& plan, const Room& room, const WorldData& data) {
    if (room.templateId != data.roomTemplate.id || room.templateVersion != data.roomTemplate.version) {
        return "its template is " + room.templateId + " v" + std::to_string(room.templateVersion) +
               ", the asset root's " + data.roomTemplate.id + " v" + std::to_string(data.roomTemplate.version);
    }
    if (room.generatorVersion.major != kGeneratorVersion.major) {
        return "it was generated by generator " + room.generatorVersion.toString() + ", this one is " +
               kGeneratorVersion.toString();
    }
    // The collection fixtures' levels must still be their prefabs': the slots a placement names exist only so.
    for (const Fixture& fixture : plan.fixtures) {
        if (fixture.id.room() != room.id ||
            (fixture.role != FixtureRole::HeroModule && fixture.role != FixtureRole::SideModule &&
             fixture.role != FixtureRole::Display)) {
            continue;
        }
        const PrefabInfo* info = data.prefabs.find(fixture.prefab);
        bool same = info != nullptr && info->levels.size() == fixture.levels.size();
        for (std::size_t i = 0; same && i < info->levels.size(); ++i) {
            const SlotLevelInfo& level = info->levels[i];
            same = fixture.levels[i] == FixtureLevel{level.level, level.slots,
                                                     detail::sectionOf(fixture.role, level.facing(data.mediaFamily))};
        }
        if (!same) {
            return "the levels of " + fixture.id.toString() + " are no longer its prefab " + fixture.prefab.manifest +
                   "'s";
        }
    }
    return {};
}

Expected<GenerationResult> updateBuilding(const BuildingUpdateInput& input, const BuildingData& building,
                                          const SystemsData& systems, std::span<const WorldData> rooms) {
    const auto refuse = [](std::string message) {
        return makeError(ErrorCode::InvalidArgument, std::move(message), "update");
    };
    if (Status status = checkWorldConfig(input.config); !status) {
        Error error = status.error();
        error.code = ErrorCode::InvalidArgument;
        return propagate(std::move(error));
    }
    const WorldPlan& stored = input.previous;
    if (stored.schemaVersion > kPlanSchemaVersion || stored.generatorVersion > kGeneratorVersion) {
        return makeError(ErrorCode::Unsupported,
                         "the plan was written by a newer Retroverse (schema " + std::to_string(stored.schemaVersion) +
                             ", generator " + stored.generatorVersion.toString() + ")",
                         "update");
    }
    if (stored.library != input.library) {
        return refuse("the plan is of library " + stored.library.str() + ", not " + input.library.str());
    }
    // The digest before is the stored file's (ADR-0013 §5): a schema-1 plan has no text this program writes.
    std::string digestBefore = input.previousDigest;
    if (digestBefore.empty()) {
        if (stored.schemaVersion != kPlanSchemaVersion) {
            return refuse("a schema-1 plan's digest is its file's SHA-256 (previousDigest)");
        }
        auto digest = planDigest(stored);
        if (!digest) {
            return propagate(digest.error());
        }
        digestBefore = std::move(*digest);
    }
    auto lifted = liftIfNeeded(stored, building, systems);
    if (!lifted) {
        return propagate(lifted.error());
    }
    WorldPlan previous = std::move(*lifted);
    sortPlan(previous);

    // Each selection goes to the room that holds its system's section, once: a system that has grown past the shared
    // threshold stays in its section (ADR-0013 §3: sticky). A system no room holds enters the building (I4 step 6a).
    std::map<RoomId, std::vector<const RoomSelection*>> selectionsOf;
    std::set<catalog::SystemName> selected;
    std::vector<const RoomSelection*> newSystems;
    for (const RoomSelection& selection : input.selections) {
        if (Status status = checkSelectionForm(selection); !status) {
            return propagate(status.error());
        }
        if (selection.room.kind() != RoomIdKind::System || selection.room.isExpansion()) {
            return refuse("a selection is of a system's room, room:<system>, not " + selection.room.toString());
        }
        const catalog::SystemName& system = selection.room.system();
        if (!selected.insert(system).second) {
            return refuse("two selections of the room " + selection.room.toString());
        }
        const auto room = std::find_if(previous.rooms.begin(), previous.rooms.end(), [&](const Room& candidate) {
            return std::find(candidate.sections.begin(), candidate.sections.end(), system) != candidate.sections.end();
        });
        if (room == previous.rooms.end()) {
            newSystems.push_back(&selection);
            continue;
        }
        selectionsOf[room->id].push_back(&selection);
    }
    // A shared or arcade room is updated with the selections of all its sections: the plan does not say which section
    // an unplaced game was of, and a new title's predecessor may be another section's. A room some of whose sections
    // have none is held as it is, as a room without a selection (its sections' selections given are not read), and
    // the report says so (heldRooms), naming the sections without one.
    std::vector<KeptRoom> heldRooms;
    for (auto it = selectionsOf.begin(); it != selectionsOf.end();) {
        const auto room = std::find_if(previous.rooms.begin(), previous.rooms.end(),
                                       [&](const Room& candidate) { return candidate.id == it->first; });
        if (it->second.size() == room->sections.size()) {
            ++it;
            continue;
        }
        std::string missing;
        std::size_t count = 0;
        for (const catalog::SystemName& section : room->sections) {
            if (!selected.contains(section)) {
                missing += (missing.empty() ? "" : ", ") + section.str();
                ++count;
            }
        }
        heldRooms.push_back({room->id, std::string("no selection of its section") + (count == 1 ? " " : "s ") +
                                           missing + ": the selections of its other sections are not read"});
        it = selectionsOf.erase(it);
    }
    // Every room has its data, of its recorded family.
    std::map<RoomId, const WorldData*> dataOf;
    for (const Room& room : previous.rooms) {
        const WorldData* data = roomDataOf(rooms, room);
        if (data == nullptr) {
            return refuse("no room data for " + room.id.toString());
        }
        if (data->mediaFamily.id != room.mediaFamily) {
            return refuse("the data of " + room.id.toString() + " is of the media family " + data->mediaFamily.id +
                          ", the room's is " + room.mediaFamily + " (loadRoomData() reads a room's own)");
        }
        dataOf.emplace(room.id, data);
        if (const auto selections = selectionsOf.find(room.id); selections != selectionsOf.end()) {
            for (const RoomSelection* selection : selections->second) {
                if (Status status = detail::checkRoomInput(*selection, *data, true, room.kind != RoomKind::Console);
                    !status) {
                    Error error = status.error();
                    error.code = ErrorCode::InvalidArgument;
                    return propagate(std::move(error));
                }
            }
        }
    }

    // The systems entering the building, each with its own data (loadWorldData()'s, with the data of the shared or
    // arcade room it would take a section of).
    std::vector<detail::EnteringSystem> entering;
    for (const RoomSelection* selection : newSystems) {
        auto system = detail::enteringSystem(*selection, rooms, input.platformTags, systems, building);
        if (!system) {
            return propagate(system.error());
        }
        entering.push_back(std::move(*system));
    }

    if (std::string reason = globalRegenerationReason(previous, input); !reason.empty()) {
        GenerationResult result;
        result.plan = std::move(previous);
        result.changes.outcome = GenerationOutcome::RequiresExplicitRegeneration;
        result.changes.rebuild = RebuildLevel::NoRebuild;
        result.changes.kept = result.plan.placements.size();
        result.changes.regenerationReason = std::move(reason);
        result.changes.digestBefore = digestBefore;
        result.changes.digestAfter = std::move(digestBefore);
        return result;
    }

    // The inputs read: the selections of the rooms given every section's, each with its room's data (the systems
    // entering the building are added below with the data of the room they took, as a fresh building hashes them).
    std::vector<std::pair<const RoomSelection*, const WorldData*>> digestRooms;
    for (const auto& [room, selections] : selectionsOf) {
        for (const RoomSelection* selection : selections) {
            digestRooms.emplace_back(selection, dataOf.at(room));
        }
    }

    // The systems no room holds enter the building among its stored rooms (ADR-0013 §3, §7; I4 step 6a), as they enter
    // a fresh one: a section is appended to its shared or arcade room when that room stands, unless the room is given
    // no selection of some section (it is held, or not updated at all: the system then waits), a new room takes the
    // east end of the shorter row of its floor (a floor that held no room appears), and a system its floor has no
    // place for has its games unplaced for capacity. Nothing that stands moves.
    std::vector<detail::BuildingRoom> buildingRooms;
    for (const Room& room : previous.rooms) {
        detail::BuildingRoom standing;
        standing.id = room.id;
        standing.kind = room.kind;
        standing.floor = room.floor;
        standing.data = dataOf.at(room.id);
        standing.record = room;
        standing.stored = true;
        standing.closed = !selectionsOf.contains(room.id);
        buildingRooms.push_back(std::move(standing));
    }
    auto entry = detail::enterBuilding(std::move(buildingRooms), entering, input.config, building);
    if (!entry) {
        return propagate(entry.error());
    }
    digestRooms.insert(digestRooms.end(), entry->digest.begin(), entry->digest.end());
    std::set<const RoomSelection*> waiting;
    std::vector<SystemRoom> systemsWaiting;
    for (const auto& [system, room] : entry->waiting) {
        waiting.insert(system->selection);
        systemsWaiting.push_back({system->selection->room.system(), room});
    }
    // A stored room's sections now: those it had, then the systems that entered it, whose selections it is updated
    // with.
    std::map<RoomId, std::vector<catalog::SystemName>> sectionsNow;
    std::vector<SystemRoom> systemsEntered;
    for (const detail::BuildingRoom& room : entry->rooms) {
        if (!room.stored || room.entered.empty()) {
            continue;
        }
        std::vector<catalog::SystemName>& sections = sectionsNow[room.id];
        sections = room.record.sections;
        for (const detail::EnteringSystem* system : room.entered) {
            sections.push_back(system->selection->room.system());
            selectionsOf[room.id].push_back(system->selection);
            systemsEntered.push_back({system->selection->room.system(), room.id});
        }
    }
    // The applied selections, in the order given: those of the rooms updated, of the systems that entered or found no
    // place; not a waiting system's.
    std::vector<RoomSelection> applied;
    for (const RoomSelection& selection : input.selections) {
        const bool read = std::any_of(selectionsOf.begin(), selectionsOf.end(), [&](const auto& item) {
            return std::find(item.second.begin(), item.second.end(), &selection) != item.second.end();
        });
        const bool entered = std::any_of(entering.begin(), entering.end(), [&](const detail::EnteringSystem& system) {
            return system.selection == &selection;
        });
        if (read || (entered && !waiting.contains(&selection))) {
            applied.push_back(selection);
        }
    }

    // Each stored room in id order: kept, updated with its selection, or left as it is.
    WorldPlan plan = previous;
    // The capacity entries of a system that found no place before (they name a room the plan does not hold) give way
    // to what its entry decides now.
    std::set<RoomId> storedIds;
    for (const Room& room : previous.rooms) {
        storedIds.insert(room.id);
    }
    std::set<GameId> enteringGames;
    for (const detail::EnteringSystem& system : entering) {
        if (waiting.contains(system.selection)) {
            continue;
        }
        for (const RoomTitle& title : system.selection->titles) {
            enteringGames.insert(title.game);
        }
        for (const UnplacedGame& game : system.selection->unplaced) {
            enteringGames.insert(game.game);
        }
    }
    std::erase_if(plan.unplaced, [&](const UnplacedGame& game) {
        return !storedIds.contains(game.room) && enteringGames.contains(game.game);
    });
    std::vector<KeptRoom> keptRooms;
    std::vector<GameId> added;
    std::vector<GameId> handedOver;
    std::vector<LevelId> dressingRemoved;
    std::vector<SlotId> slotsFreed;
    std::vector<std::string> refused;
    bool grew = false;
    bool newItems = false;
    for (const Room& room : previous.rooms) {
        const WorldData& data = *dataOf.at(room.id);
        const auto selections = selectionsOf.find(room.id);
        const auto now = sectionsNow.find(room.id);
        const std::vector<catalog::SystemName>& roomSections = now != sectionsNow.end() ? now->second : room.sections;
        if (now != sectionsNow.end()) {
            // The new sections are appended to its record whatever becomes of its contents.
            for (Room& record : plan.rooms) {
                if (record.id == room.id) {
                    record.sections = roomSections;
                }
            }
        }
        // The room's selection: its system's, or over its sections in their order (ADR-0013 §6).
        detail::SectionIndex sections;
        std::optional<RoomSelection> merged;
        const RoomSelection* selection = nullptr;
        if (selections != selectionsOf.end()) {
            if (room.kind == RoomKind::Console) {
                selection = selections->second.front();
            } else {
                merged = detail::sectionsSelection(room.id, roomSections, selections->second, sections);
                selection = &*merged;
            }
        }
        if (std::string reason = roomKeepReason(previous, room, data); !reason.empty()) {
            keptRooms.push_back({room.id, std::move(reason)});
            if (selection == nullptr) {
                continue;
            }
            // Its contents untouched, its unplaced entries too (a duplicate keeps its representative); a game of its
            // selection that it neither places nor lists is unplaced as room-kept. The room-kept entries follow the
            // selection: those of a game no longer in it go, so an update with the same selection changes nothing.
            std::erase_if(plan.unplaced, [&](const UnplacedGame& game) {
                return game.room == room.id && game.reason == UnplacedReason::RoomKept;
            });
            std::set<GameId> held;
            for (const Placement& placement : plan.placements) {
                if (placement.slot.fixture().room() == room.id) {
                    held.insert(placement.game);
                }
            }
            for (const UnplacedGame& game : plan.unplaced) {
                if (game.room == room.id) {
                    held.insert(game.game);
                }
            }
            std::set<GameId> games;
            for (const RoomTitle& title : selection->titles) {
                games.insert(title.game);
            }
            for (const UnplacedGame& game : selection->unplaced) {
                games.insert(game.game);
            }
            for (const GameId& game : games) {
                if (!held.contains(game)) {
                    plan.unplaced.push_back({game, room.id, UnplacedReason::RoomKept, {}});
                }
            }
            continue;
        }
        if (selection == nullptr) {
            continue;
        }
        WorldPlan part = extractRoom(previous, room.id);
        part.rooms.front().sections = roomSections;
        auto update = Updater(RoomUpdateInput{*selection, input.config, input.overrides, input.aliases,
                                              std::move(part), room.kind == RoomKind::Console ? nullptr : &sections},
                              data)
                          .run();
        if (!update) {
            return propagate(update.error());
        }
        Room& updated = update->plan.rooms.front();
        updated.generatorVersion = kGeneratorVersion;
        updated.placement = followDepth(updated, building.layout);
        newItems = newItems || !update->added.empty() || !update->slotsFreed.empty();
        added.insert(added.end(), update->added.begin(), update->added.end());
        handedOver.insert(handedOver.end(), update->handedOver.begin(), update->handedOver.end());
        dressingRemoved.insert(dressingRemoved.end(), update->dressingRemoved.begin(), update->dressingRemoved.end());
        slotsFreed.insert(slotsFreed.end(), update->slotsFreed.begin(), update->slotsFreed.end());
        refused.insert(refused.end(), update->refused.begin(), update->refused.end());
        grew = grew || update->grew;
        replaceRoom(plan, room.id, std::move(update->plan));
    }
    // The new rooms, generated as a fresh building generates them (their face-out titles chosen among their own), and
    // the games of the systems that found no place.
    std::vector<RoomId> roomsAdded;
    std::vector<const WorldData*> newRoomData;
    const std::uint64_t seed = worldSeed(input.config, input.library);
    for (const detail::BuildingRoom& room : entry->rooms) {
        if (room.stored) {
            continue;
        }
        auto content = detail::generateEnteredRoom(room, input.config, seed, building);
        if (!content) {
            return propagate(content.error());
        }
        for (const Placement& placement : content->placements) {
            added.push_back(placement.game);
        }
        newItems = newItems || !content->placements.empty();
        roomsAdded.push_back(room.id);
        newRoomData.push_back(room.data);
        for (const detail::EnteringSystem* system : room.entered) {
            systemsEntered.push_back({system->selection->room.system(), room.id});
        }
        detail::appendRoom(plan, std::move(*content));
    }
    plan.unplaced.insert(plan.unplaced.end(), entry->capacity.begin(), entry->capacity.end());

    GenerationResult result;
    plan.schemaVersion = kPlanSchemaVersion;
    detail::setFloors(plan, building);
    plan.generatorVersion = detail::highestGeneratorVersion(plan);
    if (!applied.empty()) {
        plan.catalogSortKeyVersion = applied.front().catalogSortKeyVersion;
    }
    sortPlan(plan);
    // The inputDigest (provenance only) names the inputs this update read: the rooms given a selection. An update that
    // leaves a room of the building without one (the app's one room until I4 step 5a, `worldplan update --system`) and
    // changes nothing keeps the plan's provenance, which named more: an update with nothing new then writes nothing
    // whichever rooms it was given (plan still holds the previous inputDigest here).
    const bool partial = std::any_of(previous.rooms.begin(), previous.rooms.end(),
                                     [&](const Room& room) { return !selectionsOf.contains(room.id); });
    const bool keepProvenance = digestRooms.empty() || (partial && plan == previous);
    detail::BuildingDigestInput digestInput;
    digestInput.config = input.config;
    digestInput.library = input.library;
    digestInput.seed = seed;
    digestInput.building = building;
    digestInput.systems = systems;
    digestInput.platformTags = input.platformTags;
    digestInput.checkedSelections = false; // checkSelectionForm() passed
    digestInput.rooms = digestRooms;
    if (!keepProvenance) {
        auto digest = detail::buildingInputDigest(digestInput);
        if (!digest) {
            Error error = digest.error();
            error.code = ErrorCode::InvalidArgument;
            return propagate(std::move(error));
        }
        plan.inputDigest = std::move(*digest);
    }

    ChangeReport& changes = result.changes;
    changes.outcome = GenerationOutcome::Updated;
    changes.added = std::move(added);
    changes.added.insert(changes.added.end(), handedOver.begin(), handedOver.end());
    std::sort(changes.added.begin(), changes.added.end());
    // Kept: the previous placements that stand in the plan exactly as they stood (both lists sorted).
    std::vector<Placement> kept;
    std::set_intersection(previous.placements.begin(), previous.placements.end(), plan.placements.begin(),
                          plan.placements.end(), std::back_inserter(kept));
    changes.kept = kept.size();
    std::set<GameId> before;
    for (const UnplacedGame& game : previous.unplaced) {
        before.insert(game.game);
    }
    for (const UnplacedGame& game : plan.unplaced) {
        if (!before.contains(game.game) && (changes.unplaced.empty() || changes.unplaced.back() != game.game)) {
            changes.unplaced.push_back(game.game);
        }
    }
    // The fixtures, against the previous plan's (both sorted by id): a socket whose decoration a module replaced has
    // its id among the removed (the decoration) and the added (the module); a growth step's decoration that a module
    // took at once is neither.
    std::map<FixtureId, const Fixture*> previousFixtures;
    for (const Fixture& fixture : previous.fixtures) {
        previousFixtures.emplace(fixture.id, &fixture);
    }
    std::set<FixtureId> standing;
    for (const Fixture& fixture : plan.fixtures) {
        standing.insert(fixture.id);
        const auto found = previousFixtures.find(fixture.id);
        if (found == previousFixtures.end()) {
            changes.fixturesAdded.push_back(fixture.id);
        } else if (found->second->role != fixture.role || found->second->prefab != fixture.prefab) {
            changes.fixturesAdded.push_back(fixture.id);
            changes.fixturesRemoved.push_back(fixture.id);
        } else if (*found->second != fixture) {
            changes.fixturesMoved.push_back(fixture.id);
        }
    }
    for (const auto& [id, fixture] : previousFixtures) {
        if (!standing.contains(id)) {
            changes.fixturesRemoved.push_back(id);
        }
    }
    changes.fixturesAdded = sortedUnique(std::move(changes.fixturesAdded));
    changes.fixturesRemoved = sortedUnique(std::move(changes.fixturesRemoved));
    changes.fixturesMoved = sortedUnique(std::move(changes.fixturesMoved));
    changes.dressingRemoved = sortedUnique(std::move(dressingRemoved));
    changes.slotsFreed = sortedUnique(std::move(slotsFreed));
    changes.keptRooms = std::move(keptRooms);
    changes.heldRooms = std::move(heldRooms); // by room id (selectionsOf's order)
    changes.roomsAdded = sortedUnique(std::move(roomsAdded));
    changes.systemsEntered = sortedUnique(std::move(systemsEntered));
    changes.systemsWaiting = sortedUnique(std::move(systemsWaiting));
    // A slot handed to an alias's identity is a texture swap: no geometry changes for it.
    const bool geometry = newItems || !changes.dressingRemoved.empty() || !changes.fixturesAdded.empty() ||
                          !changes.fixturesRemoved.empty() || !changes.fixturesMoved.empty() ||
                          plan.lights != previous.lights;
    changes.rebuild =
        grew ? RebuildLevel::RoomExpansion : (geometry ? RebuildLevel::LocalReflow : RebuildLevel::NoRebuild);

    std::vector<RoomTemplate> templates;
    std::vector<const WorldData*> datas;
    for (const auto& [room, data] : dataOf) {
        templates.push_back(data->roomTemplate);
        datas.push_back(data);
    }
    for (const WorldData* data : newRoomData) {
        templates.push_back(data->roomTemplate);
        datas.push_back(data);
    }
    const PinCheck pins = checkPins(plan, templates, input.overrides);
    changes.orphanedPins = pins.orphaned;
    changes.needsConfirmation = std::move(refused);
    changes.needsConfirmation.insert(changes.needsConfirmation.end(), pins.unhonoured.begin(),
                                     pins.unhonoured.end());
    changes.needsConfirmation = sortedUnique(std::move(changes.needsConfirmation));
    changes.digestBefore = std::move(digestBefore);
    if (stored.schemaVersion == kPlanSchemaVersion && plan == previous) {
        changes.digestAfter = changes.digestBefore;
    } else {
        // The text savePlan() writes (with the writer's check by the reader) has this digest.
        auto after = detail::sortedPlanDigest(plan);
        if (!after) {
            return propagate(after.error());
        }
        changes.digestAfter = std::move(*after);
    }
    // The pins the update never applies (unhonoured ones) are reported, not judged: a plan that already did not
    // honour them is kept updatable.
    result.validation = validatePlan(plan, detail::buildingValidationContext(plan, input.config, applied, datas,
                                                                             building, pins.honouredOrOrphaned,
                                                                             changes.keptRooms));
    result.plan = std::move(plan);
    return result;
}

Expected<GenerationResult> update(const UpdateInput& input, const WorldData& data) {
    BuildingUpdateInput building;
    building.library = input.library;
    building.selections = {input.selection};
    building.config = input.config;
    building.overrides = input.overrides;
    building.previous = input.previous;
    building.previousDigest = input.previousDigest;
    building.aliases = input.aliases;
    return updateBuilding(building, data.building, data.systems, std::span<const WorldData>(&data, 1));
}

