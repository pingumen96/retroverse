/// The order of titles within a section (ADR-0010 §6): catalog sort key, title key, GameId; in a shared or arcade room
/// after the title's system's section (ADR-0013 §6), so that a new title's predecessor is in its own section.
struct TitleKey {
    std::uint32_t section = 0;
    std::string sortKey;
    std::string titleKey;
    GameId game;

    auto operator<=>(const TitleKey&) const = default;
};

/// A spine-out level of a collection module, in the section's fill order.
struct SpineLevel {
    FixtureId fixture;
    std::uint32_t level = 0;
    std::uint32_t slots = 0;
    /// Per slot: a game stands there; shelf dressing covers it.
    std::vector<bool> taken;
    std::vector<bool> dressed;
};

/// A slot of the fill order: its level's index in it and the slot's index in the level.
struct Cell {
    std::size_t level = 0;
    std::uint32_t index = 0;
};

/// The selection's form as readRoomSelection() would accept it (the update computes its input digest without that
/// reader's check, for its time budget): a rule name and a sort-key version, the titles valid and in strict priority
/// order with no game twice, the unplaced games valid, of the room, sorted strictly, a representative exactly for a
/// duplicate. Errors: InvalidArgument naming the problem.
Status checkSelectionForm(const RoomSelection& selection) {
    const auto refuse = [](std::string message) {
        return makeError(ErrorCode::InvalidArgument, std::move(message), "update");
    };
    if (!isValidRuleName(selection.titleKeyRule) || selection.catalogSortKeyVersion < 1 ||
        selection.catalogSortKeyVersion > 999'999 || selection.room.empty()) {
        return refuse("the selection's room, title-key rule or sort-key version is malformed");
    }
    if (selection.distinctTitles < selection.titles.size()) {
        return refuse("the selection counts fewer distinct titles than titles");
    }
    std::vector<GameId> games;
    for (std::size_t i = 0; i < selection.titles.size(); ++i) {
        const RoomTitle& title = selection.titles[i];
        if (!title.game.isValid() || (title.ratingTenths && (*title.ratingTenths < 0 || *title.ratingTenths > 10))) {
            return refuse("a title of the selection is malformed: " + title.game.toString());
        }
        if (i > 0 && !priorityLess(selection.titles[i - 1], title)) {
            return refuse("the selection's titles are not in priority order at " + title.game.toString());
        }
        games.push_back(title.game);
    }
    std::sort(games.begin(), games.end());
    if (std::adjacent_find(games.begin(), games.end()) != games.end()) {
        return refuse("a game is twice among the selection's titles");
    }
    for (std::size_t i = 0; i < selection.unplaced.size(); ++i) {
        const UnplacedGame& game = selection.unplaced[i];
        const bool duplicate = game.reason == UnplacedReason::DuplicateTitle;
        if (!game.game.isValid() || game.room != selection.room || duplicate != game.representative.isValid() ||
            (i > 0 && !(selection.unplaced[i - 1] < game))) {
            return refuse("an unplaced game of the selection is malformed or out of order: " + game.game.toString());
        }
    }
    return ok();
}

/// Why the previous building cannot be updated by these rules at all, or nothing (ADR-0013 §5: the world-level checks
/// stay global): another generator major, seed, preset, random algorithm or title-key rule, or a room given a
/// selection whose seed is not the world seed's.
std::string globalRegenerationReason(const WorldPlan& previous, const BuildingUpdateInput& input) {
    const std::uint64_t seed = worldSeed(input.config, input.library);
    if (previous.generatorVersion.major != kGeneratorVersion.major) {
        return "the plan was generated by generator " + previous.generatorVersion.toString() + ", this one is " +
               kGeneratorVersion.toString() + " (another major version places games differently)";
    }
    if (previous.seed != seed) {
        return "the world seed is " + std::to_string(seed) + ", the plan's " + std::to_string(previous.seed);
    }
    if (previous.preset != input.config.preset) {
        return "the preset is " + input.config.preset + ", the plan's " + previous.preset;
    }
    if (previous.randomAlgorithm != core::kRandomAlgorithm) {
        return "the random algorithm is " + std::string(core::kRandomAlgorithm) + ", the plan's " +
               previous.randomAlgorithm;
    }
    for (const RoomSelection& selection : input.selections) {
        if (previous.titleKeyRule != selection.titleKeyRule) {
            return "the title-key rule is " + selection.titleKeyRule + ", the plan's " + previous.titleKeyRule;
        }
    }
    for (const Room& room : previous.rooms) {
        if (room.seed != roomSeed(seed, room.id)) {
            return "the seed of " + room.id.toString() + " is not the world seed's";
        }
    }
    return {};
}

/// The room `room` of `building` with its elements, as a plan of that one room (the header kept).
WorldPlan extractRoom(const WorldPlan& building, const RoomId& room) {
    WorldPlan part = building;
    part.floors.clear();
    std::erase_if(part.rooms, [&](const Room& candidate) { return candidate.id != room; });
    std::erase_if(part.fixtures, [&](const Fixture& fixture) { return fixture.id.room() != room; });
    std::erase_if(part.placements,
                  [&](const Placement& placement) { return placement.slot.fixture().room() != room; });
    std::erase_if(part.dressing,
                  [&](const DressedLevel& dressed) { return dressed.level.fixture().room() != room; });
    std::erase_if(part.lights, [&](const PlanLight& light) { return light.id.room() != room; });
    std::erase_if(part.unplaced, [&](const UnplacedGame& game) { return game.room != room; });
    return part;
}

/// `building` with the room `room` and its elements replaced by those of `part` (a plan of that one room).
void replaceRoom(WorldPlan& building, const RoomId& room, WorldPlan&& part) {
    std::erase_if(building.rooms, [&](const Room& candidate) { return candidate.id == room; });
    std::erase_if(building.fixtures, [&](const Fixture& fixture) { return fixture.id.room() == room; });
    std::erase_if(building.placements,
                  [&](const Placement& placement) { return placement.slot.fixture().room() == room; });
    std::erase_if(building.dressing,
                  [&](const DressedLevel& dressed) { return dressed.level.fixture().room() == room; });
    std::erase_if(building.lights, [&](const PlanLight& light) { return light.id.room() == room; });
    std::erase_if(building.unplaced, [&](const UnplacedGame& game) { return game.room == room; });
    detail::appendRoom(building, std::move(part));
}

/// What one room's update reads.
struct RoomUpdateInput {
    /// The room's selection: its system's, or a shared or arcade room's over its sections (sectionsSelection()).
    const RoomSelection& selection;
    const WorldConfig& config;
    const WorldOverrides& overrides;
    const std::vector<GameAlias>& aliases;
    /// The room as it stands, a plan of that one room.
    WorldPlan previous;
    /// A shared or arcade room's titles' sections; null for a console room.
    const detail::SectionIndex* sections = nullptr;
};

/// What one room's update gives: the room as a plan of that one room, and what the building's report needs of it.
struct RoomUpdate {
    WorldPlan plan;
    std::vector<GameId> added;
    std::vector<GameId> handedOver;
    std::vector<LevelId> dressingRemoved;
    std::vector<SlotId> slotsFreed;
    std::vector<std::string> refused;
    bool grew = false;
};

class Updater {
public:
    Updater(const RoomUpdateInput& input, const WorldData& data)
        : m_input(input), m_data(data), m_template(data.roomTemplate), m_previous(input.previous) {
        sortPlan(m_previous);
        m_plan = m_previous;
    }

    Expected<RoomUpdate> run() {
        m_room = &m_plan.rooms.front();
        m_layoutInput.emplace(detail::LayoutInput{m_template, m_data.platform, m_data.mediaFamily, m_data.prefabs,
                                                  m_room->id, m_room->seed, {},
                                                  m_input.config.decorationDensityPermille});
        m_layoutInput->counts.growthSteps = m_room->growthSteps;
        for (const Placement& placement : m_plan.placements) {
            m_placed.emplace(placement.game, placement);
        }
        protectPinnedFixtures();
        applyAliases();
        classifySelection();
        buildFillOrder();
        indexSpineTitles();

        std::sort(m_newTitles.begin(), m_newTitles.end(),
                  [this](const RoomTitle* a, const RoomTitle* b) { return keyOf(*a) < keyOf(*b); });
        for (const RoomTitle* title : m_newTitles) {
            auto placed = placeNewTitle(*title);
            if (!placed) {
                return propagate(placed.error());
            }
            if (!*placed) {
                m_unplaced.push_back({title->game, m_room->id, UnplacedReason::Capacity, {}});
            }
        }
        if (m_lightsDirty) {
            placeWallWashersAgain();
        }
        return finish();
    }

private:
    TitleKey keyOf(const RoomTitle& title) const {
        return {detail::sectionOf(m_input.sections, title.game), title.sortKey, title.titleKey, title.game};
    }

    bool isPlaced(const GameId& game) const { return m_placed.contains(game); }

    void refuse(std::string change) { m_refused.push_back(std::move(change)); }

    /// The sockets whose fixtures are pinned and stand in the plan: a module never replaces them, and a growth that
    /// would move one of the south wall is not taken.
    void protectPinnedFixtures() {
        for (const FixturePin& pin : m_input.overrides.fixturePins) {
            const bool stands = std::any_of(m_plan.fixtures.begin(), m_plan.fixtures.end(),
                                            [&](const Fixture& fixture) { return fixture.id == pin.fixture; });
            if (stands && pin.fixture.room() == m_room->id) {
                m_pinnedSockets.insert(pin.fixture.socket());
            }
        }
    }

    /// An alias hands its slot to the identity it stands for when that one has none, else frees it (ADR-0010 §10).
    void applyAliases() {
        std::vector<GameAlias> aliases = m_input.aliases;
        std::sort(aliases.begin(), aliases.end());
        for (const GameAlias& alias : aliases) {
            const auto found = m_placed.find(alias.alias);
            if (alias.alias == alias.target || !alias.target.isValid() || found == m_placed.end()) {
                continue;
            }
            Placement placement = found->second;
            m_placed.erase(found);
            if (isPlaced(alias.target)) {
                freeSlot(placement.slot);
                continue;
            }
            // The item stands as it stood: the slot and its offset are kept, only the game it shows changes.
            placement.game = alias.target;
            m_placed.emplace(alias.target, placement);
            m_handedOver.push_back(alias.target);
        }
    }

    const Fixture* fixtureOf(const FixtureId& id) const {
        for (const Fixture& fixture : m_plan.fixtures) {
            if (fixture.id == id) {
                return &fixture;
            }
        }
        return nullptr;
    }

    /// A slot whose game is gone: a spine-out one becomes reserve, a face-out one is dressed (it stays free until a
    /// regeneration: the face-out set never changes incrementally).
    void freeSlot(const SlotId& slot) {
        m_slotsFreed.push_back(slot);
        const Fixture* fixture = fixtureOf(slot.fixture());
        if (fixture == nullptr) {
            return;
        }
        for (const FixtureLevel& level : fixture->levels) {
            if (level.level == slot.level() && isFaceOut(level.section) && !m_template.shelfDressing.empty()) {
                DressedLevel dressed;
                dressed.level = slot.levelId();
                dressed.firstSlot = slot.index();
                dressed.count = 1;
                dressed.prop = detail::dressingProp(m_room->seed, dressed.level, m_template.shelfDressing);
                m_plan.dressing.push_back(std::move(dressed));
            }
        }
    }

    /// Which selection titles a placed game represents, which are new, which stay unplaced for capacity; the unplaced
    /// games of the selection with their representatives.
    void classifySelection() {
        const RoomSelection& selection = m_input.selection;
        std::map<GameId, std::vector<GameId>> versionsOf; // a title's other versions, by its representative
        for (const UnplacedGame& game : selection.unplaced) {
            if (game.reason == UnplacedReason::DuplicateTitle) {
                versionsOf[game.representative].push_back(game.game);
            }
        }
        std::set<GameId> titles;
        for (const RoomTitle& title : selection.titles) {
            titles.insert(title.game);
        }
        std::map<GameId, GameId> previousRepresentative;
        std::set<GameId> previousCapacity;
        for (const UnplacedGame& game : m_previous.unplaced) {
            if (game.reason == UnplacedReason::DuplicateTitle) {
                previousRepresentative.emplace(game.game, game.representative);
            } else if (game.reason == UnplacedReason::Capacity) {
                previousCapacity.insert(game.game);
            }
        }
        for (const RoomTitle& title : selection.titles) {
            if (isPlaced(title.game)) {
                m_keys[title.game] = keyOf(title);
                continue;
            }
            std::vector<GameId> members{title.game};
            if (const auto versions = versionsOf.find(title.game); versions != versionsOf.end()) {
                members.insert(members.end(), versions->second.begin(), versions->second.end());
            }
            std::optional<GameId> representative;
            for (const GameId& member : members) {
                if (isPlaced(member) && (!representative || member < *representative)) {
                    representative = member;
                }
            }
            // The previous plan's choice: a version listed then as a duplicate of a placed game that is no title of
            // the selection now (gone, unavailable, hidden) is still that game's title.
            for (const GameId& member : members) {
                const auto before = previousRepresentative.find(member);
                if (!representative && before != previousRepresentative.end() && isPlaced(before->second) &&
                    !titles.contains(before->second)) {
                    representative = before->second;
                }
            }
            if (representative) {
                m_representedBy.emplace(title.game, *representative);
                m_keys.emplace(*representative, keyOf(title));
            } else if (previousCapacity.contains(title.game)) {
                m_unplaced.push_back({title.game, m_room->id, UnplacedReason::Capacity, {}});
            } else {
                m_newTitles.push_back(&title);
            }
        }
        for (const UnplacedGame& game : selection.unplaced) {
            if (isPlaced(game.game)) {
                continue; // it keeps its slot (no cover now, unavailable, or a version of a title it represents)
            }
            UnplacedGame entry = game;
            if (entry.reason == UnplacedReason::DuplicateTitle) {
                if (const auto by = m_representedBy.find(entry.representative); by != m_representedBy.end()) {
                    entry.representative = by->second;
                }
            }
            m_unplaced.push_back(entry);
        }
        for (const auto& [title, representative] : m_representedBy) {
            m_unplaced.push_back({title, m_room->id, UnplacedReason::DuplicateTitle, representative});
        }
    }

    /// The collection modules in the collection's order, then any other by id.
    std::vector<const Fixture*> modulesInOrder() const {
        std::vector<const Fixture*> modules;
        for (const Fixture& fixture : m_plan.fixtures) {
            if (fixture.role == FixtureRole::HeroModule || fixture.role == FixtureRole::SideModule) {
                modules.push_back(&fixture);
            }
        }
        const auto rank = [&](const Fixture* fixture) {
            const auto& order = m_template.collectionOrder;
            return static_cast<std::size_t>(std::find(order.begin(), order.end(), fixture->id.socket()) -
                                            order.begin());
        };
        std::stable_sort(modules.begin(), modules.end(), [&](const Fixture* a, const Fixture* b) {
            return std::pair(rank(a), a->id) < std::pair(rank(b), b->id);
        });
        return modules;
    }

    /// The spine-out section's levels in fill order with what stands on them.
    void buildFillOrder() {
        m_fill.clear();
        m_levelIndex.clear();
        for (const Fixture* module : modulesInOrder()) {
            const PrefabInfo* info = m_data.prefabs.find(module->prefab);
            if (info == nullptr) {
                continue; // roomKeepReason() made sure of every collection fixture's prefab
            }
            std::vector<LevelFacing> facings;
            for (const SlotLevelInfo& level : info->levels) {
                facings.push_back(level.facing(m_data.mediaFamily));
            }
            for (const std::size_t index : detail::bandOrder(info->levels, facings, m_template.eyeHeightMm)) {
                const SlotLevelInfo& level = info->levels[index];
                SpineLevel spine;
                spine.fixture = module->id;
                spine.level = level.level;
                spine.slots = level.slots;
                spine.taken.assign(level.slots, false);
                spine.dressed.assign(level.slots, false);
                m_levelIndex.emplace(std::pair(module->id, level.level), m_fill.size());
                m_fill.push_back(std::move(spine));
            }
        }
        for (const auto& [game, placement] : m_placed) {
            if (const auto level = levelOf(placement.slot); level && placement.slot.index() < m_fill[*level].slots) {
                m_fill[*level].taken[placement.slot.index()] = true;
            }
        }
        for (const DressedLevel& dressed : m_plan.dressing) {
            const auto level = m_levelIndex.find(std::pair(dressed.level.fixture(), dressed.level.level()));
            if (level == m_levelIndex.end()) {
                continue;
            }
            SpineLevel& spine = m_fill[level->second];
            for (std::uint32_t i = dressed.firstSlot; i < dressed.firstSlot + dressed.count && i < spine.slots; ++i) {
                spine.dressed[i] = true;
            }
        }
    }

    std::optional<std::size_t> levelOf(const SlotId& slot) const {
        const auto found = m_levelIndex.find(std::pair(slot.fixture(), slot.level()));
        return found != m_levelIndex.end() ? std::optional(found->second) : std::nullopt;
    }

    /// The spine-out titles with a known place in the alphabet, in that order, for the predecessors.
    void indexSpineTitles() {
        for (const auto& [game, placement] : m_placed) {
            const auto key = m_keys.find(game);
            if (key != m_keys.end() && levelOf(placement.slot)) {
                m_spine.push_back({key->second, placement.slot});
            }
        }
        std::sort(m_spine.begin(), m_spine.end());
    }

    /// The first slot from `from` on (wrapping round to the section's start) that is free and dressed or not, as
    /// asked.
    std::optional<Cell> firstFree(const Cell& from, bool dressed) const {
        const auto fits = [&](const SpineLevel& level, std::uint32_t index) {
            return !level.taken[index] && level.dressed[index] == dressed;
        };
        for (std::size_t level = from.level; level < m_fill.size(); ++level) {
            for (std::uint32_t index = level == from.level ? from.index : 0; index < m_fill[level].slots; ++index) {
                if (fits(m_fill[level], index)) {
                    return Cell{level, index};
                }
            }
        }
        for (std::size_t level = 0; level <= from.level && level < m_fill.size(); ++level) {
            const std::uint32_t slots = m_fill[level].slots;
            const std::uint32_t end = level == from.level ? std::min(from.index, slots) : slots;
            for (std::uint32_t index = 0; index < end; ++index) {
                if (fits(m_fill[level], index)) {
                    return Cell{level, index};
                }
            }
        }
        return std::nullopt;
    }

    /// Where the search for a new title starts: just after its alphabetical predecessor's slot, else the section's
    /// first slot.
    Cell startFor(const TitleKey& key) const {
        const auto after = std::lower_bound(m_spine.begin(), m_spine.end(), key,
                                            [](const std::pair<TitleKey, SlotId>& entry, const TitleKey& wanted) {
                                                return entry.first < wanted;
                                            });
        if (after == m_spine.begin()) {
            return {};
        }
        const SlotId& slot = std::prev(after)->second;
        const auto level = levelOf(slot);
        return level ? Cell{*level, slot.index() + 1} : Cell{};
    }

    /// Places a new title (the file's header), adding a module or growing the room when the section is full. False
    /// when even the template's limit holds no more.
    Expected<bool> placeNewTitle(const RoomTitle& title) {
        const TitleKey key = keyOf(title);
        for (;;) {
            const Cell start = startFor(key);
            if (auto cell = firstFree(start, false)) {
                place(*cell, title, key);
                return true;
            }
            if (auto cell = firstFree(start, true)) {
                undress(*cell);
                place(*cell, title, key);
                return true;
            }
            auto added = addSideModule();
            if (!added) {
                return propagate(added.error());
            }
            if (*added) {
                continue;
            }
            if (!grow()) {
                return false;
            }
        }
    }

    void place(const Cell& cell, const RoomTitle& title, const TitleKey& key) {
        SpineLevel& level = m_fill[cell.level];
        Placement placement;
        placement.slot = *SlotId::make(level.fixture, level.level, cell.index);
        placement.game = title.game;
        detail::setPlacementOffset(placement, m_room->seed, m_data.mediaFamily.id, false);
        level.taken[cell.index] = true;
        m_keys[title.game] = key;
        m_spine.insert(std::upper_bound(m_spine.begin(), m_spine.end(), std::pair(key, placement.slot)),
                       std::pair(key, placement.slot));
        m_placed.emplace(title.game, placement);
        m_added.push_back(title.game);
    }

    /// A dressed level gives way to a title: every span of dressing on it removed.
    void undress(const Cell& cell) {
        SpineLevel& level = m_fill[cell.level];
        const LevelId id = *LevelId::make(level.fixture, level.level);
        std::erase_if(m_plan.dressing, [&](const DressedLevel& dressed) { return dressed.level == id; });
        level.dressed.assign(level.slots, false);
        m_dressingRemoved.push_back(id);
    }

    bool hasModuleIn(const std::string& socket) const {
        return std::any_of(m_plan.fixtures.begin(), m_plan.fixtures.end(), [&](const Fixture& fixture) {
            return fixture.id.socket() == socket && fixture.role == FixtureRole::SideModule;
        });
    }

    /// A side-wall module in the next side-wall socket of the collection's order that holds none (its decoration
    /// removed, every level dressed). False when no socket of the room's growth is left.
    Expected<bool> addSideModule() {
        for (const std::string& socketId : m_template.collectionOrder) {
            const TemplateSocket* socket = m_template.socket(socketId);
            if (socket == nullptr || socket->kind != SocketKind::SideWall || socket->growthStep > m_room->growthSteps ||
                hasModuleIn(socketId)) {
                continue;
            }
            if (m_pinnedSockets.contains(socketId)) {
                // Reported once: the report's lists are made unique.
                refuse("socket " + socketId +
                       ": a side-wall module would replace a pinned fixture; it went to the next socket");
                continue;
            }
            auto module = detail::sideModuleIn(*m_layoutInput, *socket);
            if (!module) {
                return propagate(module.error());
            }
            std::erase_if(m_plan.fixtures, [&](const Fixture& fixture) { return fixture.id.socket() == socketId; });
            // A lamp standing there took its light with it; the wall-washers are placed again below.
            std::erase_if(m_plan.lights, [&](const PlanLight& light) { return light.id.socket() == socketId; });
            Fixture fixture = std::move(module->fixture);
            if (!m_template.shelfDressing.empty()) {
                for (const FixtureLevel& level : fixture.levels) {
                    DressedLevel dressed;
                    dressed.level = *LevelId::make(fixture.id, level.level);
                    dressed.firstSlot = 0;
                    dressed.count = level.slots;
                    dressed.prop = detail::dressingProp(m_room->seed, dressed.level, m_template.shelfDressing);
                    m_plan.dressing.push_back(std::move(dressed));
                }
            }
            m_plan.fixtures.push_back(std::move(fixture));
            m_lightsDirty = true;
            buildFillOrder();
            return true;
        }
        return false;
    }

    /// One more growth step (ADR-0010 §4): the south wall and what stands on it move south, the step's side-wall sockets
    /// are decorated. False at the template's limit, or when it would move a pinned fixture.
    bool grow() {
        if (m_grownOut || m_room->growthSteps >= m_template.maxGrowthSteps()) {
            return false;
        }
        std::set<std::string> southSockets;
        for (const TemplateSocket& socket : m_template.sockets) {
            if (socket.wall == Wall::South) {
                southSockets.insert(socket.id);
            }
        }
        for (const std::string& socket : m_pinnedSockets) {
            if (southSockets.contains(socket)) {
                refuse("growth: the room would grow and move the pinned fixture of socket " + socket +
                       "; the titles that need it are unplaced for capacity");
                m_grownOut = true;
                return false;
            }
        }
        const std::uint32_t growth = m_room->growthSteps + 1;
        const Footprint interior = interiorFootprint(m_template, growth);
        m_room->growthSteps = growth;
        m_room->minXMm = interior.minXMm;
        m_room->maxXMm = interior.maxXMm;
        m_room->minZMm = interior.minZMm;
        m_room->maxZMm = interior.maxZMm;
        m_layoutInput->counts.growthSteps = growth;
        for (Fixture& fixture : m_plan.fixtures) {
            if (southSockets.contains(fixture.id.socket())) {
                fixture.zMm += m_template.growthStepMm;
            }
        }
        for (PlanLight& light : m_plan.lights) {
            if (southSockets.contains(light.id.socket())) {
                light.zMm += m_template.growthStepMm;
                light.targetZMm += m_template.growthStepMm;
            }
        }
        for (const std::string& socketId : m_template.collectionOrder) {
            const TemplateSocket* socket = m_template.socket(socketId);
            if (socket == nullptr || socket->kind != SocketKind::SideWall || socket->growthStep != growth) {
                continue;
            }
            const std::size_t limit = std::min(m_template.lightLimit, kMaxSceneLights);
            const std::size_t left = limit - std::min(limit, m_plan.lights.size());
            if (auto decoration = detail::decorationIn(*m_layoutInput, *socket, left, m_plan.fixtures)) {
                m_plan.fixtures.push_back(std::move(decoration->fixture.fixture));
                if (decoration->light) {
                    m_plan.lights.push_back(*decoration->light);
                }
            }
        }
        m_grew = true;
        return true;
    }

    /// The wall-washers over the modules as they stand now, within the lights the others leave (fixture_layout.hpp).
    void placeWallWashersAgain() {
        std::erase_if(m_plan.lights, [](const PlanLight& light) { return light.role == LightRole::WallWasher; });
        std::vector<detail::ModuleOnWall> modules;
        for (const Fixture* module : modulesInOrder()) {
            if (const TemplateSocket* socket = m_template.socket(module->id.socket())) {
                modules.push_back({socket, module->depthMm});
            }
        }
        const std::size_t limit = std::min(m_template.lightLimit, kMaxSceneLights);
        const std::size_t budget = limit - std::min(limit, m_plan.lights.size());
        for (const PlanLight& light : detail::wallWasherLights(*m_layoutInput, modules, budget)) {
            m_plan.lights.push_back(light);
        }
    }

    RoomUpdate finish() {
        RoomUpdate update;
        WorldPlan& plan = m_plan;
        plan.placements.clear();
        for (const auto& [game, placement] : m_placed) {
            plan.placements.push_back(placement);
        }
        plan.unplaced = std::move(m_unplaced);
        sortPlan(plan);
        update.plan = std::move(plan);
        update.added = std::move(m_added);
        update.handedOver = std::move(m_handedOver);
        update.dressingRemoved = std::move(m_dressingRemoved);
        update.slotsFreed = std::move(m_slotsFreed);
        update.refused = std::move(m_refused);
        update.grew = m_grew;
        return update;
    }

    const RoomUpdateInput& m_input;
    const WorldData& m_data;
    const RoomTemplate& m_template;
    WorldPlan m_previous;
    WorldPlan m_plan;
    Room* m_room = nullptr;
    std::optional<detail::LayoutInput> m_layoutInput;

    std::map<GameId, Placement> m_placed;
    std::map<GameId, TitleKey> m_keys;
    std::map<GameId, GameId> m_representedBy;
    std::vector<const RoomTitle*> m_newTitles;
    std::vector<UnplacedGame> m_unplaced;
    std::set<std::string> m_pinnedSockets;

    std::vector<SpineLevel> m_fill;
    std::map<std::pair<FixtureId, std::uint32_t>, std::size_t> m_levelIndex;
    std::vector<std::pair<TitleKey, SlotId>> m_spine;

    std::vector<GameId> m_added;
    std::vector<GameId> m_handedOver;
    std::vector<LevelId> m_dressingRemoved;
    std::vector<SlotId> m_slotsFreed;
    std::vector<std::string> m_refused;
    bool m_lightsDirty = false;
    bool m_grew = false;
    bool m_grownOut = false;
};

/// The list without its repeated elements, sorted.
template <class T>
std::vector<T> sortedUnique(std::vector<T> list) {
    std::sort(list.begin(), list.end());
    list.erase(std::unique(list.begin(), list.end()), list.end());
    return list;
}

/// The data of `room` among `rooms` (by the system of its first section): a shared or arcade room's when that system's
/// data is a console room's that carries it with the room's recorded family and theme pack (WorldData::sharedRoom).
const WorldData* roomDataOf(std::span<const WorldData> rooms, const Room& room) noexcept {
    const catalog::SystemName& system = room.sections.empty() ? room.id.system() : room.sections.front();
    const WorldData* data = detail::dataOf(rooms, system);
    const WorldData* shared = data != nullptr ? data->sharedRoom.get() : nullptr;
    if (data != nullptr && data->kind != room.kind && shared != nullptr && shared->kind == room.kind &&
        shared->mediaFamily.id == room.mediaFamily && shared->platform.themePack == room.themePack) {
        return shared;
    }
    return data;
}

